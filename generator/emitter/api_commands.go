func formatCallArgBranch(p indexer.CommandParam, idx *indexer.Index) string {
	if p.IsString || p.IsStringSlice {
		return fmt.Sprintf("uintptr(unsafe.Pointer(c_%s))", p.GoName)
	}
	if p.IsSlice {
		baseElemType := strings.TrimPrefix(p.GoHighType, "[]")
		baseElemType = strings.TrimPrefix(baseElemType, "*")
		vkName := "Vk" + baseElemType
		if _, isStruct := idx.Structs[vkName]; isStruct {
			return fmt.Sprintf("uintptr(unsafe.Pointer(SliceData(c_%s)))", p.GoName)
		}
		return fmt.Sprintf("uintptr(unsafe.Pointer(c_%s))", p.GoName)
	}
	if p.IsPointer && strings.HasPrefix(p.GoHighType, "*") {
		baseType := strings.TrimPrefix(p.GoHighType, "*")
		vkName := "Vk" + baseType
		if _, isStruct := idx.Structs[vkName]; isStruct {
			return fmt.Sprintf("uintptr(unsafe.Pointer(c_%s))", p.GoName)
		}
		return fmt.Sprintf("uintptr(unsafe.Pointer(%s))", p.GoName)
	}
	if p.IsPointer {
		return fmt.Sprintf("uintptr(unsafe.Pointer(%s))", p.GoName)
	}
	return fmt.Sprintf("uintptr(%s)", p.GoName)
}

