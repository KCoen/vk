func findSingleOutputParam(c *indexer.CommandInfo) *indexer.CommandParam {
	if c.IsOutputQuery {
		return nil
	}
	var outP *indexer.CommandParam
	for i := range c.Params {
		p := &c.Params[i]
		if p.IsOutputSingle {
			if outP != nil {
				return nil
			}
			outP = p
		}
	}
	return outP
}

func sortStrings(s []string) {
	sort.Strings(s)
}

func qualifyType(typeName string) string {
	if typeName == "" || typeName == "void" {
		return ""
	}
	if strings.HasPrefix(typeName, "[]") {
		elem := strings.TrimPrefix(typeName, "[]")
		return "[]" + qualifyType(elem)
	}
	stars := ""
	for strings.HasPrefix(typeName, "*") {
		stars += "*"
		typeName = strings.TrimPrefix(typeName, "*")
	}
	return stars + qualifySingleType(typeName)
}

func qualifySingleType(t string) string {
	switch t {
	case "uint8", "uint16", "uint32", "uint64", "int8", "int16", "int32", "int64", "float32", "float64", "byte", "string", "uintptr", "unsafe.Pointer":
		return t
	default:
		return "vulkan." + t
	}
}
