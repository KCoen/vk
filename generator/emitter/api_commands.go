func emitStandardCommandBranch(sb *strings.Builder, c *indexer.CommandInfo, idx *indexer.Index, isMethod bool) {
	var inParams []string
	for _, p := range c.Params {
		if p.IsCountParam && p.PairedSliceParam != "" {
			continue
		}
		inParams = append(inParams, fmt.Sprintf("%s %s", p.GoName, p.GoHighType))
	}

	returnType := ""
	if c.ReturnGoType != "void" && c.ReturnGoType != "" {
		if strings.HasPrefix(c.ReturnGoType, "PFN_") {
			returnType = "uintptr"
		} else {
			returnType = c.ReturnGoType
		}
	}

	retSignature := ""
	if returnType != "" {
		retSignature = fmt.Sprintf(" (result %s)", returnType)
	}

	fnPtr := fmt.Sprintf("pfn%s", c.GoName)
	if isMethod {
		sb.WriteString(fmt.Sprintf("func (c *Commands) %s(%s)%s {\n", c.GoName, strings.Join(inParams, ", "), retSignature))
		fnPtr = fmt.Sprintf("c.pfn%s", c.GoName)
	} else {
		sb.WriteString(fmt.Sprintf("func %s(%s)%s {\n", c.GoName, strings.Join(inParams, ", "), retSignature))
	}

	emitParamConversionsBranch(sb, c.Params, idx)

	var callArgs []string
	for _, p := range c.Params {
		if p.IsCountParam && p.PairedSliceParam != "" {
			callArgs = append(callArgs, fmt.Sprintf("uintptr(len(%s))", indexer.CleanParamName(p.PairedSliceParam)))
		} else {
			callArgs = append(callArgs, formatCallArgBranch(p, idx))
		}
	}

	if returnType != "" {
		sb.WriteString(fmt.Sprintf("\tr1, _, _ := CallSyscall(%s, %s)\n", fnPtr, strings.Join(callArgs, ", ")))
		if returnType == "uintptr" {
			sb.WriteString("\treturn r1\n")
		} else {
			sb.WriteString(fmt.Sprintf("\treturn %s(r1)\n", returnType))
		}
	} else {
		sb.WriteString(fmt.Sprintf("\tCallSyscall(%s, %s)\n", fnPtr, strings.Join(callArgs, ", ")))
	}
	sb.WriteString("}\n\n")
}

func emitStandardCommandExt(sb *strings.Builder, c *indexer.CommandInfo, idx *indexer.Index, isMethod bool) {
	var inParams []string
	for _, p := range c.Params {
		if p.IsCountParam && p.PairedSliceParam != "" {
			continue
		}
		inParams = append(inParams, fmt.Sprintf("%s %s", p.GoName, qualifyType(p.GoHighType)))
	}

	returnType := ""
	if c.ReturnGoType != "void" && c.ReturnGoType != "" {
		if strings.HasPrefix(c.ReturnGoType, "PFN_") {
			returnType = "uintptr"
		} else {
			returnType = qualifyType(c.ReturnGoType)
		}
	}

	retSignature := ""
	if returnType != "" {
		retSignature = fmt.Sprintf(" (result %s)", returnType)
	}

	fnPtr := fmt.Sprintf("pfn%s", c.GoName)
	if isMethod {
		sb.WriteString(fmt.Sprintf("func (c *Commands) %s(%s)%s {\n", c.GoName, strings.Join(inParams, ", "), retSignature))
		fnPtr = fmt.Sprintf("c.pfn%s", c.GoName)
	} else {
		sb.WriteString(fmt.Sprintf("func %s(%s)%s {\n", c.GoName, strings.Join(inParams, ", "), retSignature))
	}

	emitParamConversionsExt(sb, c.Params, idx)

	var callArgs []string
	for _, p := range c.Params {
		if p.IsCountParam && p.PairedSliceParam != "" {
			callArgs = append(callArgs, fmt.Sprintf("uintptr(len(%s))", indexer.CleanParamName(p.PairedSliceParam)))
		} else {
			callArgs = append(callArgs, formatCallArgExt(p, idx))
		}
	}

	if returnType != "" {
		sb.WriteString(fmt.Sprintf("\tr1, _, _ := vulkan.CallSyscall(%s, %s)\n", fnPtr, strings.Join(callArgs, ", ")))
		if returnType == "uintptr" {
			sb.WriteString("\treturn r1\n")
		} else {
			sb.WriteString(fmt.Sprintf("\treturn %s(r1)\n", returnType))
		}
	} else {
		sb.WriteString(fmt.Sprintf("\tvulkan.CallSyscall(%s, %s)\n", fnPtr, strings.Join(callArgs, ", ")))
	}
	sb.WriteString("}\n\n")
}

func emitParamConversionsBranch(sb *strings.Builder, params []indexer.CommandParam, idx *indexer.Index, omitNames ...string) {
	omitMap := make(map[string]bool)
	for _, n := range omitNames {
		omitMap[n] = true
	}
	for _, p := range params {
		if omitMap[p.Name] || p.IsCountParam {
			continue
		}
		if p.IsString {
			sb.WriteString(fmt.Sprintf("\tc_%s := StringToNullTerminated(%s)\n", p.GoName, p.GoName))
		} else if p.IsStringSlice {
			sb.WriteString(fmt.Sprintf("\tc_%s := StringSliceToNullTerminated(%s)\n", p.GoName, p.GoName))
		} else if p.IsSlice {
			baseElemType := strings.TrimPrefix(p.GoHighType, "[]")
			baseElemType = strings.TrimPrefix(baseElemType, "*")
			vkName := "Vk" + baseElemType
			if _, isStruct := idx.Structs[vkName]; isStruct {
				sb.WriteString(fmt.Sprintf("\tc_%s := make([]Raw%s, len(%s))\n", p.GoName, baseElemType, p.GoName))
				sb.WriteString(fmt.Sprintf("\tfor i := range %s {\n", p.GoName))
				sb.WriteString(fmt.Sprintf("\t\tif raw := %s[i].Raw(); raw != nil {\n\t\t\tc_%s[i] = *raw\n\t\t}\n", p.GoName, p.GoName))
				sb.WriteString("\t}\n")
			} else {
				sb.WriteString(fmt.Sprintf("\tc_%s := SliceData(%s)\n", p.GoName, p.GoName))
			}
		} else if p.IsPointer && strings.HasPrefix(p.GoHighType, "*") {
			baseType := strings.TrimPrefix(p.GoHighType, "*")
			vkName := "Vk" + baseType
			if _, isStruct := idx.Structs[vkName]; isStruct {
				sb.WriteString(fmt.Sprintf("\tc_%s := %s.Raw()\n", p.GoName, p.GoName))
			}
		}
	}
}

