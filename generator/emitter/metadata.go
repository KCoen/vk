package emitter

import (
	"fmt"
	"sort"
	"strings"

	"go.cld.moe/vk_google/generator/indexer"
)

// EmitBranchMetadata generates metadata_gen.go for an API branch package (vulkan, vulkanbase, vulkansc).
func EmitBranchMetadata(branch *indexer.ApiBranchInfo, idx *indexer.Index) (string, error) {
	var sb strings.Builder

	sb.WriteString("// Code generated by vk-gen. DO NOT EDIT.\n\n")
	sb.WriteString(fmt.Sprintf("package %s\n\n", branch.PkgName))

	// Format metadata structure
	sb.WriteString("// XMLFormatProperties holds XML metadata describing a Vulkan format.\n")
	sb.WriteString("type XMLFormatProperties struct {\n")
	sb.WriteString("\tName           string\n")
	sb.WriteString("\tClass          string\n")
	sb.WriteString("\tBlockSize      string\n")
	sb.WriteString("\tTexelsPerBlock string\n")
	sb.WriteString("\tPacked         string\n")
	sb.WriteString("}\n\n")

	sb.WriteString("// FormatsMetadata maps format names to their XML metadata properties.\n")
	sb.WriteString("var FormatsMetadata = map[Format]XMLFormatProperties{\n")

	var fmtNames []string
	for name := range idx.Formats {
		fmtNames = append(fmtNames, name)
	}
	sort.Strings(fmtNames)

	for _, name := range fmtNames {
		f := idx.Formats[name]
		goName := indexer.CleanEnumName(f.Name)
		if eg, ok := branch.EnumGroups["VkFormat"]; ok {
			found := false
			for _, v := range eg.Values {
				if v.GoName == goName {
					found = true
					break
				}
			}
			if !found {
				continue
			}
		} else {
			continue
		}
		sb.WriteString(fmt.Sprintf("\t%s: {\n", goName))
		sb.WriteString(fmt.Sprintf("\t\tName: \"%s\",\n", f.Name))
		sb.WriteString(fmt.Sprintf("\t\tClass: \"%s\",\n", f.Class))
		sb.WriteString(fmt.Sprintf("\t\tBlockSize: \"%s\",\n", f.BlockSize))
		sb.WriteString(fmt.Sprintf("\t\tTexelsPerBlock: \"%s\",\n", f.TexelsPerBlock))
		sb.WriteString(fmt.Sprintf("\t\tPacked: \"%s\",\n", f.Packed))
		sb.WriteString("\t},\n")
	}
	sb.WriteString("}\n\n")

	// Sync Stages metadata
	sb.WriteString("// SyncStageMetadata holds synchronization stage metadata.\n")
	sb.WriteString("type SyncStageMetadata struct {\n")
	sb.WriteString("\tName    string\n")
	sb.WriteString("\tAlias   string\n")
	sb.WriteString("\tSupport string\n")
	sb.WriteString("}\n\n")

	sb.WriteString("// SyncStages maps sync stage names to metadata.\n")
	sb.WriteString("var SyncStages = map[string]SyncStageMetadata{\n")
	var stageNames []string
	for name := range idx.SyncStages {
		stageNames = append(stageNames, name)
	}
	sort.Strings(stageNames)
	for _, name := range stageNames {
		s := idx.SyncStages[name]
		sb.WriteString(fmt.Sprintf("\t\"%s\": {\n\t\tName: \"%s\",\n\t\tAlias: \"%s\",\n\t\tSupport: \"%s\",\n\t},\n", name, s.Name, s.Alias, s.Support))
	}
	sb.WriteString("}\n\n")

	// Sync Access metadata
	sb.WriteString("// SyncAccessMetadata holds synchronization access mask metadata.\n")
	sb.WriteString("type SyncAccessMetadata struct {\n")
	sb.WriteString("\tName    string\n")
	sb.WriteString("\tAlias   string\n")
	sb.WriteString("\tSupport string\n")
	sb.WriteString("}\n\n")

	sb.WriteString("// SyncAccesses maps sync access names to metadata.\n")
	sb.WriteString("var SyncAccesses = map[string]SyncAccessMetadata{\n")
	var accessNames []string
	for name := range idx.SyncAccesses {
		accessNames = append(accessNames, name)
	}
	sort.Strings(accessNames)
	for _, name := range accessNames {
		a := idx.SyncAccesses[name]
		sb.WriteString(fmt.Sprintf("\t\"%s\": {\n\t\tName: \"%s\",\n\t\tAlias: \"%s\",\n\t\tSupport: \"%s\",\n\t},\n", name, a.Name, a.Alias, a.Support))
	}
	sb.WriteString("}\n")

	return sb.String(), nil
}
