package emitter

import (
	"fmt"
	"sort"
	"strings"

	"go.cld.moe/vk_google/generator/indexer"
)

// EmitBranchEnums generates enums_gen.go for an API branch package (vulkan, vulkanbase, vulkansc).
func EmitBranchEnums(branch *indexer.ApiBranchInfo, idx *indexer.Index) (string, error) {
	var sb strings.Builder

	sb.WriteString("// Code generated by vk-gen. DO NOT EDIT.\n\n")
	sb.WriteString(fmt.Sprintf("package %s\n\n", branch.PkgName))
	sb.WriteString("import \"fmt\"\n\n")

	var groupNames []string
	for name := range branch.EnumGroups {
		groupNames = append(groupNames, name)
	}
	sort.Strings(groupNames)

	for _, name := range groupNames {
		eg := branch.EnumGroups[name]
		if eg.Type == "bitmask" {
			// Handled in bitmasks.go
			continue
		}

		typeKind := "int32"
		if eg.Bitwidth == 64 {
			typeKind = "int64"
		}

		lead := fmt.Sprintf("%s represents %s.", eg.GoName, eg.Name)
		if eg.ShortDesc != "" {
			lead = fmt.Sprintf("%s - %s (%s).", eg.GoName, eg.ShortDesc, eg.Name)
		} else if eg.Comment != "" {
			lead = fmt.Sprintf("%s - %s (%s).", eg.GoName, eg.Comment, eg.Name)
		}

		doc := FormatDocComment(lead, "Documented at: "+FormatVulkanDocLink(name))
		sb.WriteString(doc)
		sb.WriteString(fmt.Sprintf("type %s %s\n\n", eg.GoName, typeKind))

		if len(eg.Values) > 0 {
			sb.WriteString("const (\n")

			valueMap := make(map[string]bool)
			for _, v := range eg.Values {
				if !v.IsAlias && v.GoName != "" {
					valueMap[v.GoName] = true
				}
			}

			seenValues := make(map[string]bool)
			for _, v := range eg.Values {
				if seenValues[v.GoName] {
					continue
				}
				if v.IsAlias && !valueMap[v.AliasOf] {
					continue
				}
				seenValues[v.GoName] = true

				comment := v.Comment
				if comment != "" {
					comment = " // " + strings.TrimSpace(comment)
				}

				if v.IsAlias && v.AliasOf != "" {
					sb.WriteString(fmt.Sprintf("\t%s %s = %s%s\n", v.GoName, eg.GoName, v.AliasOf, comment))
				} else if v.ValueStr != "" {
					sb.WriteString(fmt.Sprintf("\t%s %s = %s%s\n", v.GoName, eg.GoName, v.ValueStr, comment))
				}
			}
			sb.WriteString(")\n\n")

			// String() method
			sb.WriteString(fmt.Sprintf("// String returns the string representation of %s.\n", eg.GoName))
			sb.WriteString(fmt.Sprintf("func (e %s) String() string {\n", eg.GoName))
			sb.WriteString("\tswitch e {\n")

			seenInts := make(map[string]bool)
			for _, v := range eg.Values {
				if v.IsAlias || v.ValueStr == "" {
					continue
				}
				if seenInts[v.ValueStr] {
					continue
				}
				seenInts[v.ValueStr] = true
				sb.WriteString(fmt.Sprintf("\tcase %s:\n\t\treturn \"%s\"\n", v.GoName, v.Name))
			}
			sb.WriteString(fmt.Sprintf("\tdefault:\n\t\treturn fmt.Sprintf(\"%s(%%d)\", e)\n", eg.GoName))
			sb.WriteString("\t}\n}\n\n")
		}
	}

	// Emit Enum Type Aliases
	var aliasNames []string
	for name, a := range branch.TypeAliases {
		if a.Category == "enum" {
			aliasNames = append(aliasNames, name)
		}
	}
	sort.Strings(aliasNames)

	if len(aliasNames) > 0 {
		sb.WriteString("// --- Enum Type Aliases ---\n\n")
		for _, name := range aliasNames {
			a := idx.TypeAliases[name]
			doc := FormatDocComment(fmt.Sprintf("%s is an alias of %s.", a.GoName, a.GoAlias),
				a.Comment,
				"Documented at: "+FormatVulkanDocLink(name),
			)
			sb.WriteString(doc)
			sb.WriteString(fmt.Sprintf("type %s = %s\n\n", a.GoName, a.GoAlias))
		}
	}

	return sb.String(), nil
}
