package emitter

import (
	"fmt"
	"sort"
	"strings"

	"github.com/KCoen/vk/generator/indexer"
)

// EmitBranchTypes generates the types_gen.go file for an API branch package (vulkan, vulkanbase, vulkansc).
func EmitBranchTypes(branch *indexer.ApiBranchInfo, idx *indexer.Index) (string, error) {
	var sb strings.Builder

	sb.WriteString("// Code generated by vk-gen. DO NOT EDIT.\n\n")
	sb.WriteString(fmt.Sprintf("package %s\n\n", branch.PkgName))
	sb.WriteString("import (\n")
	sb.WriteString("\t\"fmt\"\n")
	sb.WriteString("\t\"unsafe\"\n")
	sb.WriteString(")\n\n")

	sb.WriteString("// Basic Vulkan primitive types\n")
	sb.WriteString("type (\n")
	sb.WriteString("\t// Bool32 is a Vulkan 32-bit boolean type.\n")
	sb.WriteString("\tBool32 uint32\n\n")
	sb.WriteString("\t// DeviceSize is a Vulkan size type for memory allocations and buffer offsets.\n")
	sb.WriteString("\tDeviceSize uint64\n\n")
	sb.WriteString("\t// DeviceAddress is a Vulkan 64-bit device address type.\n")
	sb.WriteString("\tDeviceAddress uint64\n\n")
	sb.WriteString("\t// Flags is a 32-bit bitmask type.\n")
	sb.WriteString("\tFlags uint32\n\n")
	sb.WriteString("\t// Flags64 is a 64-bit bitmask type.\n")
	sb.WriteString("\tFlags64 uint64\n\n")
	sb.WriteString("\t// SampleMask is a 32-bit sample mask type.\n")
	sb.WriteString("\tSampleMask uint32\n\n")
	sb.WriteString("\t// RemoteAddressNV is a generic pointer type.\n")
	sb.WriteString("\tRemoteAddressNV unsafe.Pointer\n")
	sb.WriteString(")\n\n")

	sb.WriteString("const (\n")
	sb.WriteString("\tTrue  Bool32 = 1\n")
	sb.WriteString("\tFalse Bool32 = 0\n")
	sb.WriteString("\tNullHandle = 0\n")
	sb.WriteString(")\n\n")

	sb.WriteString("// Bool converts Bool32 to Go bool.\n")
	sb.WriteString("func (b Bool32) Bool() bool {\n")
	sb.WriteString("\treturn b != 0\n")
	sb.WriteString("}\n\n")

	sb.WriteString("// FromBool converts Go bool to Bool32.\n")
	sb.WriteString("func FromBool(b bool) Bool32 {\n")
	sb.WriteString("\tif b {\n\t\treturn True\n\t}\n\treturn False\n")
	sb.WriteString("}\n\n")

	// Handles
	sb.WriteString("// --- Vulkan Handles ---\n\n")

	var handleNames []string
	for name := range branch.Handles {
		handleNames = append(handleNames, name)
	}
	sort.Strings(handleNames)

	for _, name := range handleNames {
		h := branch.Handles[name]
		doc := FormatDocComment(fmt.Sprintf("%s is a Vulkan %s handle.", h.GoName, name),
			h.Comment,
			"Documented at: "+FormatVulkanDocLink(name),
		)
		sb.WriteString(doc)

		if h.Kind == indexer.HandleDispatchable {
			sb.WriteString(fmt.Sprintf("type %s uintptr\n\n", h.GoName))
			sb.WriteString(fmt.Sprintf("// IsValid returns true if the %s handle is not NULL.\n", h.GoName))
			sb.WriteString(fmt.Sprintf("func (h %s) IsValid() bool {\n\treturn h != 0\n}\n\n", h.GoName))
			sb.WriteString(fmt.Sprintf("// Handle returns the underlying uintptr value.\n"))
			sb.WriteString(fmt.Sprintf("func (h %s) Handle() uintptr {\n\treturn uintptr(h)\n}\n\n", h.GoName))
			sb.WriteString(fmt.Sprintf("// String formats the handle as a hex string.\n"))
			sb.WriteString(fmt.Sprintf("func (h %s) String() string {\n\treturn fmt.Sprintf(\"%s(0x%%X)\", uintptr(h))\n}\n\n", h.GoName, h.GoName))
		} else {
			sb.WriteString(fmt.Sprintf("type %s uint64\n\n", h.GoName))
			sb.WriteString(fmt.Sprintf("// IsValid returns true if the %s handle is not NULL.\n", h.GoName))
			sb.WriteString(fmt.Sprintf("func (h %s) IsValid() bool {\n\treturn h != 0\n}\n\n", h.GoName))
			sb.WriteString(fmt.Sprintf("// Handle returns the underlying uint64 value.\n"))
			sb.WriteString(fmt.Sprintf("func (h %s) Handle() uint64 {\n\treturn uint64(h)\n}\n\n", h.GoName))
			sb.WriteString(fmt.Sprintf("// String formats the handle as a hex string.\n"))
			sb.WriteString(fmt.Sprintf("func (h %s) String() string {\n\treturn fmt.Sprintf(\"%s(0x%%X)\", uint64(h))\n}\n\n", h.GoName, h.GoName))
		}
	}

	// Handle and Basetype Aliases
	var aliasNames []string
	for name, a := range branch.TypeAliases {
		if a.Category == "handle" || a.Category == "basetype" || a.Category == "" {
			aliasNames = append(aliasNames, name)
		}
	}
	sort.Strings(aliasNames)

	if len(aliasNames) > 0 {
		sb.WriteString("// --- Handle and Type Aliases ---\n\n")
		for _, name := range aliasNames {
			a := branch.TypeAliases[name]
			doc := FormatDocComment(fmt.Sprintf("%s is an alias of %s.", a.GoName, a.GoAlias),
				a.Comment,
				"Documented at: "+FormatVulkanDocLink(name),
			)
			sb.WriteString(doc)
			sb.WriteString(fmt.Sprintf("type %s = %s\n\n", a.GoName, a.GoAlias))
		}
	}

	// Function Pointers (Callbacks)
	var fpNames []string
	for name := range branch.FuncPointerDefs {
		fpNames = append(fpNames, name)
	}
	sort.Strings(fpNames)

	if len(fpNames) > 0 {
		sb.WriteString("// --- Function Pointer (Callback) Types ---\n\n")
		for _, name := range fpNames {
			fp := branch.FuncPointerDefs[name]
			if fp == nil {
				fp = idx.FuncPointerDefs[name]
			}
			if fp != nil {
				valid := true
				for _, p := range fp.Params {
					if !isValidBranchType(p.GoType, branch, idx) {
						valid = false
						break
					}
				}
				if fp.ReturnGoType != "void" && fp.ReturnGoType != "" && !isValidBranchType(fp.ReturnGoType, branch, idx) {
					valid = false
				}
				if !valid {
					continue
				}

				doc := FormatDocComment(fmt.Sprintf("%s is a Vulkan function pointer / callback type.", name),
					"Documented at: "+FormatVulkanDocLink(name),
				)
				sb.WriteString(doc)

				var params []string
				for _, p := range fp.Params {
					params = append(params, fmt.Sprintf("%s %s", p.GoName, p.GoType))
				}
				retStr := ""
				if fp.ReturnGoType != "void" && fp.ReturnGoType != "" {
					retStr = " " + fp.ReturnGoType
				}
				sb.WriteString(fmt.Sprintf("type %s func(%s)%s\n\n", name, strings.Join(params, ", "), retStr))
			} else {
				doc := FormatDocComment(fmt.Sprintf("%s is a Vulkan function pointer / callback type.", name),
					"Documented at: "+FormatVulkanDocLink(name),
				)
				sb.WriteString(doc)
				sb.WriteString(fmt.Sprintf("type %s func()\n\n", name))
			}
		}
	}

	return sb.String(), nil
}
