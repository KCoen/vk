package emitter

import (
	"fmt"
	"strings"

	"github.com/KCoen/vk/generator/indexer"
)

// EmitExtensionPackage generates all files for a specific Vulkan extension package.
func EmitExtensionPackage(ext *indexer.ExtensionInfo, idx *indexer.Index) (map[string]string, error) {
	files := make(map[string]string)

	// doc.go
	var docParts []string
	if ext.Author != "" {
		docParts = append(docParts, "Author: "+ext.Author)
	}
	if ext.Contact != "" {
		docParts = append(docParts, "Contact: "+ext.Contact)
	}
	if ext.PromotedTo != "" {
		docParts = append(docParts, "Promoted to: "+ext.PromotedTo)
	}
	if ext.DeprecatedBy != "" {
		docParts = append(docParts, "Deprecated by: "+ext.DeprecatedBy)
	}
	if ext.Platform != "" {
		docParts = append(docParts, "Platform: "+ext.Platform)
	}
	if ext.Comment != "" {
		docParts = append(docParts, ext.Comment)
	}
	if idx.DocIndex != nil && idx.DocIndex.ExtensionDocs != nil {
		if overview, ok := idx.DocIndex.ExtensionDocs[ext.Name]; ok && overview != "" {
			docParts = append(docParts, "\n"+overview)
		}
	}

	docContent := fmt.Sprintf("// Code generated by vk-gen. DO NOT EDIT.\n\n%spackage %s\n",
		FormatDocComment(fmt.Sprintf("Package %s provides bindings for the %s extension.", ext.PkgName, ext.Name), docParts...),
		ext.PkgName,
	)
	files["doc_gen.go"] = docContent

	// extension_gen.go (constants)
	var extConstSb strings.Builder
	extConstSb.WriteString("// Code generated by vk-gen. DO NOT EDIT.\n\n")
	extConstSb.WriteString(fmt.Sprintf("package %s\n\n", ext.PkgName))
	extConstSb.WriteString("const (\n")
	extConstSb.WriteString(fmt.Sprintf("\tExtensionName = \"%s\"\n", ext.Name))
	if ext.Number > 0 {
		extConstSb.WriteString(fmt.Sprintf("\tExtensionNumber = %d\n", ext.Number))
	}
	extConstSb.WriteString(")\n")
	files["extension_gen.go"] = extConstSb.String()

	// commands_gen.go (if the extension has commands)
	if len(ext.Commands) > 0 {
		cmds, err := EmitExtensionCommands(ext, idx)
		if err != nil {
			return nil, err
		}
		files["commands_gen.go"] = cmds
	}

	return files, nil
}
