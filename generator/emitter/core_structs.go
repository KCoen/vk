package emitter

import (
	"fmt"
	"strings"

	"github.com/KCoen/vk/generator/indexer"
)

// EmitBranchStructs generates structs_gen.go for an API branch package (vulkan, vulkanbase, vulkansc).
func EmitBranchStructs(branch *indexer.ApiBranchInfo, idx *indexer.Index) (string, error) {
	var sb strings.Builder

	sb.WriteString("// Code generated by vk-gen. DO NOT EDIT.\n\n")
	sb.WriteString(fmt.Sprintf("package %s\n\n", branch.PkgName))
	sb.WriteString("import (\n")
	sb.WriteString("\t\"unsafe\"\n\n")
	sb.WriteString("\t\"github.com/ebitengine/purego\"\n")
	sb.WriteString(")\n\n")
	sb.WriteString("var _ = purego.NewCallback\n\n")

	structNames := make([]string, 0, len(branch.Structs))
	for name, s := range branch.Structs {
		if s == nil || s.IsAlias {
			continue
		}
		structNames = append(structNames, name)
	}
	sortStrings(structNames)

	for _, name := range structNames {
		s := branch.Structs[name]

		if s.Category == "union" {
			emitUnion(&sb, s, idx, branch)
		} else {
			emitStruct(&sb, s, idx, branch)
		}
	}

	// Emit struct aliases
	aliasNames := make([]string, 0)
	for name, a := range branch.TypeAliases {
		if (a.Category == "struct" || a.Category == "union") && isValidBranchType(a.AliasOf, branch, idx) {
			aliasNames = append(aliasNames, name)
		}
	}
	sortStrings(aliasNames)

	for _, name := range aliasNames {
		a := branch.TypeAliases[name]
		doc := FormatDocComment(
			fmt.Sprintf("%s is alias for %s (%s).", a.GoName, a.GoAlias, a.AliasOf),
			a.Comment,
			"Documented at: "+FormatVulkanDocLink(a.Name),
		)
		sb.WriteString(doc)
		sb.WriteString(fmt.Sprintf("type %s = %s\n", a.GoName, a.GoAlias))
		sb.WriteString(fmt.Sprintf("type Raw%s = Raw%s\n\n", a.GoName, a.GoAlias))
	}

	return sb.String(), nil
}

func emitStruct(sb *strings.Builder, s *indexer.StructInfo, idx *indexer.Index, branch *indexer.ApiBranchInfo) {
	doc := FormatStructDocComment(s)

	hasSTypeDefault := false
	if s.HasSType && s.GoSTypeDefault != "" {
		if eg, ok := branch.EnumGroups["VkStructureType"]; ok {
			for _, v := range eg.Values {
				if v.GoName == s.GoSTypeDefault {
					hasSTypeDefault = true
					break
				}
			}
		}
	}

	// 1. Emit Raw struct (C-ABI compatible)
	sb.WriteString(FormatDocComment(fmt.Sprintf("Raw%s is the C-ABI memory layout for %s.", s.GoName, s.Name)))
	sb.WriteString(fmt.Sprintf("type Raw%s struct {\n", s.GoName))
	for _, m := range s.Members {
		if m.Api != "" && !indexer.ApiMatches(m.Api, branch.Name) {
			continue
		}
		if !isValidBranchType(m.GoRawType, branch, idx) {
			continue
		}
		rawFieldType := resolveRawFieldType(m, idx)
		fDoc := CleanFieldDocComment(m)
		if m.Name == "sType" || m.GoName == "SType" {
			if hasSTypeDefault {
				fDoc = fmt.Sprintf("is %s", s.GoSTypeDefault)
			} else {
				fDoc = "is a StructureType value identifying this structure."
			}
		}
		if fDoc != "" {
			sb.WriteString(fmt.Sprintf("\t%s %s // %s\n", m.GoName, rawFieldType, fDoc))
		} else {
			sb.WriteString(fmt.Sprintf("\t%s %s\n", m.GoName, rawFieldType))
		}
	}
	sb.WriteString("}\n\n")

	// 2. Emit Idiomatic Go struct
	sb.WriteString(doc)
	sb.WriteString(fmt.Sprintf("type %s struct {\n", s.GoName))
	for _, m := range s.Members {
		if m.Api != "" && !indexer.ApiMatches(m.Api, branch.Name) {
			continue
		}
		if !isValidBranchType(m.GoHighType, branch, idx) {
			continue
		}
		// If this member is purely a count member for a slice, omit it from the high-level struct
		if isOmittedCountMember(m, s) {
			continue
		}

		highFieldType := resolveHighFieldType(m, idx)
		fDoc := CleanFieldDocComment(m)
		if m.Name == "sType" || m.GoName == "SType" {
			if hasSTypeDefault {
				fDoc = fmt.Sprintf("is %s", s.GoSTypeDefault)
			} else {
				fDoc = "is a StructureType value identifying this structure."
			}
		}
		if fDoc != "" {
			sb.WriteString(fmt.Sprintf("\t%s %s // %s\n", m.GoName, highFieldType, fDoc))
		} else {
			sb.WriteString(fmt.Sprintf("\t%s %s\n", m.GoName, highFieldType))
		}
	}
	sb.WriteString("}\n\n")

	// 3. Emit Constructor with automatic sType
	if s.HasSType && hasSTypeDefault {
		sb.WriteString(FormatDocComment(fmt.Sprintf("New%s creates an initialized %s with default SType.", s.GoName, s.GoName)))
		sb.WriteString(fmt.Sprintf("func New%s() *%s {\n", s.GoName, s.GoName))
		sb.WriteString(fmt.Sprintf("\treturn &%s{\n\t\tSType: %s,\n\t}\n}\n\n", s.GoName, s.GoSTypeDefault))
	}

	// 4. Emit SetDefaults() method
	if s.HasSType && hasSTypeDefault {
		sb.WriteString(FormatDocComment(fmt.Sprintf("SetDefaults initializes SType to %s if zero.", s.GoSTypeDefault)))
		sb.WriteString(fmt.Sprintf("func (s *%s) SetDefaults() {\n", s.GoName))
		sb.WriteString(fmt.Sprintf("\tif s.SType == 0 {\n\t\ts.SType = %s\n\t}\n}\n\n", s.GoSTypeDefault))
	}

	// 5. Emit SetNext() method & Extender interface
	if s.HasNext {
		extList := idx.StructExtensions[s.Name]
		var branchExtList []string
		for _, extName := range extList {
			vkName := "Vk" + extName
			if _, ok := branch.Structs[vkName]; ok {
				branchExtList = append(branchExtList, extName)
			} else if _, ok := branch.TypeAliases[vkName]; ok {
				branchExtList = append(branchExtList, extName)
			}
		}
		canonicalExtList := getCanonicalExtenders(branchExtList, idx)

		if len(canonicalExtList) > 0 {
			// Emit Extender interface for this struct
			sb.WriteString(FormatDocComment(fmt.Sprintf("%sExtender is implemented by all structs that can extend %s in a pNext chain.", s.GoName, s.GoName)))
			sb.WriteString(fmt.Sprintf("type %sExtender interface {\n\tis%sExtender()\n}\n\n", s.GoName, s.GoName))

			for _, extName := range canonicalExtList {
				sb.WriteString(fmt.Sprintf("func (*%s) is%sExtender() {}\n", extName, s.GoName))
			}
			sb.WriteString("\n")

			var docLines []string
			docLines = append(docLines, "SetNext chains an extension structure to the Next pointer with compile-time type safety.")
			docLines = append(docLines, "")
			docLines = append(docLines, fmt.Sprintf("Valid extension types for %s include:", s.GoName))
			for _, extName := range canonicalExtList {
				docLines = append(docLines, fmt.Sprintf("  - *%s", extName))
			}
			sb.WriteString(FormatDocComment(strings.Join(docLines, "\n")))
			sb.WriteString(fmt.Sprintf("func (s *%s) SetNext(ext %sExtender) {\n", s.GoName, s.GoName))
			sb.WriteString("\ts.Next = ext\n}\n\n")
		} else {
			sb.WriteString(FormatDocComment(fmt.Sprintf("SetNext chains an extension structure to the Next pointer.")))
			sb.WriteString(fmt.Sprintf("func (s *%s) SetNext(ext any) {\n", s.GoName))
			sb.WriteString("\ts.Next = ext\n}\n\n")
		}
	}

	// 6. Emit Raw() conversion method
	emitRawConversion(sb, s, idx, branch)
}

func getCanonicalExtenders(extList []string, idx *indexer.Index) []string {
	seen := make(map[string]bool)
	var result []string
	for _, extName := range extList {
		canon := extName
		vkName := "Vk" + extName
		if sInfo, ok := idx.Structs[vkName]; ok && sInfo.IsAlias && sInfo.AliasOf != "" {
			canon = indexer.CleanTypeName(sInfo.AliasOf)
		}
		if aInfo, ok := idx.TypeAliases[vkName]; ok && aInfo.GoAlias != "" {
			canon = aInfo.GoAlias
		}
		if !seen[canon] {
			seen[canon] = true
			result = append(result, canon)
		}
	}
	sortStrings(result)
	return result
}

func emitUnion(sb *strings.Builder, s *indexer.StructInfo, idx *indexer.Index, branch *indexer.ApiBranchInfo) {
	doc := FormatDocComment(fmt.Sprintf("%s is union %s.", s.GoName, s.Name),
		s.Comment,
		"Documented at: "+FormatVulkanDocLink(s.Name),
	)
	sb.WriteString(doc)
	sb.WriteString(fmt.Sprintf("type %s struct {\n", s.GoName))
	// Primary union field
	if len(s.Members) > 0 {
		m := s.Members[0]
		highFieldType := resolveHighFieldType(m, idx)
		sb.WriteString(fmt.Sprintf("\t%s %s\n", m.GoName, highFieldType))
	}
	sb.WriteString("}\n\n")

	// Accessor methods for other union members
	for i := 1; i < len(s.Members); i++ {
		m := s.Members[i]
		highFieldType := resolveHighFieldType(m, idx)
		sb.WriteString(fmt.Sprintf("// %s returns pointer to %s as %s.\n", m.GoName, m.GoName, highFieldType))
		sb.WriteString(fmt.Sprintf("func (u *%s) %s() *%s {\n", s.GoName, m.GoName, highFieldType))
		sb.WriteString(fmt.Sprintf("\treturn (*%s)(unsafe.Pointer(u))\n}\n\n", highFieldType))
	}

	sb.WriteString(fmt.Sprintf("type Raw%s = %s\n\n", s.GoName, s.GoName))
	sb.WriteString(fmt.Sprintf("// Raw converts %s into its C-ABI Raw%s representation.\n", s.GoName, s.GoName))
	sb.WriteString(fmt.Sprintf("func (u *%s) Raw() *Raw%s {\n\tif u == nil {\n\t\treturn nil\n\t}\n\treturn u\n}\n\n", s.GoName, s.GoName))
	sb.WriteString(fmt.Sprintf("func (u *%s) rawPointer() unsafe.Pointer {\n\tif u == nil {\n\t\treturn nil\n\t}\n\treturn unsafe.Pointer(u.Raw())\n}\n\n", s.GoName))
}

func isOmittedCountMember(m indexer.StructMember, s *indexer.StructInfo) bool {
	if m.IsPointer || m.IsString || m.IsStringSlice {
		return false
	}
	// Check if this member serves as SliceCountMember for any other member
	for _, other := range s.Members {
		if (other.IsSlice || other.IsStringSlice) && other.SliceCountMember == m.Name {
			if other.Name == "pImmutableSamplers" {
				continue
			}
			return true
		}
	}
	return false
}

func resolveRawFieldType(m indexer.StructMember, idx *indexer.Index) string {
	if m.Name == "pNext" || m.GoName == "Next" {
		return "unsafe.Pointer"
	}
	if m.IsFuncPointer {
		return "uintptr"
	}
	base := m.GoRawType
	if strings.HasPrefix(base, "**") {
		trimmed := strings.TrimPrefix(base, "**")
		vkName := "Vk" + trimmed
		if _, isStruct := idx.Structs[vkName]; isStruct {
			base = "**Raw" + trimmed
		}
	} else if strings.HasPrefix(base, "*") {
		trimmed := strings.TrimPrefix(base, "*")
		vkName := "Vk" + trimmed
		if _, isStruct := idx.Structs[vkName]; isStruct {
			base = "*Raw" + trimmed
		}
	} else {
		vkName := "Vk" + base
		if _, isStruct := idx.Structs[vkName]; isStruct && len(m.ArrayDimensions) == 0 {
			base = "Raw" + base
		}
	}
	if len(m.ArrayDimensions) > 0 {
		dimStr := ""
		for _, d := range m.ArrayDimensions {
			cleanDim := indexer.CleanConstantName(d)
			dimStr += fmt.Sprintf("[%s]", cleanDim)
		}
		baseType := base
		if strings.HasPrefix(baseType, "*") {
			baseType = baseType[1:]
		}
		return dimStr + baseType
	}
	return base
}

func resolveHighFieldType(m indexer.StructMember, idx *indexer.Index) string {
	if m.Name == "pNext" || m.GoName == "Next" {
		return "any"
	}
	if m.IsFuncPointer {
		return m.GoHighType
	}
	if m.IsStringSlice {
		return "[]string"
	}
	if m.IsString {
		return "string"
	}
	if m.IsSlice {
		return m.GoHighType
	}
	if len(m.ArrayDimensions) > 0 {
		dimStr := ""
		for _, d := range m.ArrayDimensions {
			cleanDim := indexer.CleanConstantName(d)
			dimStr += fmt.Sprintf("[%s]", cleanDim)
		}
		baseType := m.GoRawType
		if strings.HasPrefix(baseType, "*") {
			baseType = baseType[1:]
		}
		return dimStr + baseType
	}
	return m.GoHighType
}

func emitRawConversion(sb *strings.Builder, s *indexer.StructInfo, idx *indexer.Index, branch *indexer.ApiBranchInfo) {
	sb.WriteString(FormatDocComment(fmt.Sprintf("Raw converts %s into its C-ABI Raw%s representation.", s.GoName, s.GoName)))
	sb.WriteString(fmt.Sprintf("func (s *%s) Raw() *Raw%s {\n", s.GoName, s.GoName))
	sb.WriteString("\tif s == nil {\n\t\treturn nil\n\t}\n")

	hasSTypeDefault := false
	if s.HasSType && s.GoSTypeDefault != "" {
		if eg, ok := branch.EnumGroups["VkStructureType"]; ok {
			for _, v := range eg.Values {
				if v.GoName == s.GoSTypeDefault {
					hasSTypeDefault = true
					break
				}
			}
		}
	}

	if s.HasSType && hasSTypeDefault {
		sb.WriteString(fmt.Sprintf("\tsType := s.SType\n\tif sType == 0 {\n\t\tsType = %s\n\t}\n", s.GoSTypeDefault))
	} else if s.HasSType {
		sb.WriteString("\tsType := s.SType\n")
	}

	// Pre-convert callbacks
	for _, m := range s.Members {
		if m.Api != "" && !indexer.ApiMatches(m.Api, branch.Name) {
			continue
		}
		if !isValidBranchType(m.GoRawType, branch, idx) || !isValidBranchType(m.GoHighType, branch, idx) {
			continue
		}
		if m.IsFuncPointer {
			sb.WriteString(fmt.Sprintf("\tvar c_%s uintptr\n", m.GoName))
			sb.WriteString(fmt.Sprintf("\tif s.%s != nil {\n\t\tc_%s = purego.NewCallback(s.%s)\n\t}\n", m.GoName, m.GoName, m.GoName))
		}
	}

	// Pre-convert struct slices
	for _, m := range s.Members {
		if m.Api != "" && !indexer.ApiMatches(m.Api, branch.Name) {
			continue
		}
		if !isValidBranchType(m.GoRawType, branch, idx) || !isValidBranchType(m.GoHighType, branch, idx) {
			continue
		}
		if m.IsSlice {
			baseElemType := strings.TrimPrefix(m.GoHighType, "[]")
			isDoublePtr := strings.HasPrefix(baseElemType, "*")
			baseElemType = strings.TrimPrefix(baseElemType, "*")
			vkName := "Vk" + baseElemType
			if _, isStruct := idx.Structs[vkName]; isStruct {
				if isDoublePtr {
					sb.WriteString(fmt.Sprintf("\tvar raw_%s []*Raw%s\n", m.GoName, baseElemType))
					sb.WriteString(fmt.Sprintf("\tif len(s.%s) > 0 {\n", m.GoName))
					sb.WriteString(fmt.Sprintf("\t\traw_%s = make([]*Raw%s, len(s.%s))\n", m.GoName, baseElemType, m.GoName))
					sb.WriteString(fmt.Sprintf("\t\tfor i := range s.%s {\n", m.GoName))
					sb.WriteString(fmt.Sprintf("\t\t\traw_%s[i] = s.%s[i].Raw()\n", m.GoName, m.GoName))
					sb.WriteString("\t\t}\n\t}\n")
				} else {
					sb.WriteString(fmt.Sprintf("\tvar raw_%s []Raw%s\n", m.GoName, baseElemType))
					sb.WriteString(fmt.Sprintf("\tif len(s.%s) > 0 {\n", m.GoName))
					sb.WriteString(fmt.Sprintf("\t\traw_%s = make([]Raw%s, len(s.%s))\n", m.GoName, baseElemType, m.GoName))
					sb.WriteString(fmt.Sprintf("\t\tfor i := range s.%s {\n", m.GoName))
					sb.WriteString(fmt.Sprintf("\t\t\tif r := s.%s[i].Raw(); r != nil {\n\t\t\t\traw_%s[i] = *r\n\t\t\t}\n", m.GoName, m.GoName))
					sb.WriteString("\t\t}\n\t}\n")
				}
			}
		}
	}

	sb.WriteString(fmt.Sprintf("\traw := &Raw%s{\n", s.GoName))
	if s.HasSType {
		sb.WriteString("\t\tSType: sType,\n")
	}

	for _, m := range s.Members {
		if m.Api != "" && !indexer.ApiMatches(m.Api, branch.Name) {
			continue
		}
		if !isValidBranchType(m.GoRawType, branch, idx) || !isValidBranchType(m.GoHighType, branch, idx) {
			continue
		}
		if m.Name == "sType" {
			continue
		}

		if m.Name == "pNext" || m.GoName == "Next" {
			sb.WriteString("\t\tNext: ExtractRawPointer(s.Next),\n")
		} else if m.IsFuncPointer {
			sb.WriteString(fmt.Sprintf("\t\t%s: c_%s,\n", m.GoName, m.GoName))
		} else if m.IsStringSlice {
			sb.WriteString(fmt.Sprintf("\t\t%s: StringSliceToNullTerminated(s.%s),\n", m.GoName, m.GoName))
		} else if m.IsString {
			sb.WriteString(fmt.Sprintf("\t\t%s: StringToNullTerminated(s.%s),\n", m.GoName, m.GoName))
		} else if m.IsPointer && strings.HasPrefix(m.GoHighType, "**") {
			baseType := strings.TrimPrefix(m.GoHighType, "**")
			vkName := "Vk" + baseType
			if _, isStruct := idx.Structs[vkName]; isStruct {
				sb.WriteString(fmt.Sprintf("\t\t%s: (**Raw%s)(unsafe.Pointer(s.%s)),\n", m.GoName, baseType, m.GoName))
			} else {
				sb.WriteString(fmt.Sprintf("\t\t%s: s.%s,\n", m.GoName, m.GoName))
			}
		} else if m.IsPointer && strings.HasPrefix(m.GoHighType, "*") {
			baseType := strings.TrimPrefix(m.GoHighType, "*")
			vkName := "Vk" + baseType
			if _, isStruct := idx.Structs[vkName]; isStruct {
				sb.WriteString(fmt.Sprintf("\t\t%s: s.%s.Raw(),\n", m.GoName, m.GoName))
			} else {
				sb.WriteString(fmt.Sprintf("\t\t%s: s.%s,\n", m.GoName, m.GoName))
			}
		} else if m.IsSlice {
			baseElemType := strings.TrimPrefix(m.GoHighType, "[]")
			baseElemType = strings.TrimPrefix(baseElemType, "*")
			vkName := "Vk" + baseElemType
			if _, isStruct := idx.Structs[vkName]; isStruct {
				if m.GoRawType == "unsafe.Pointer" {
					sb.WriteString(fmt.Sprintf("\t\t%s: unsafe.Pointer(SliceData(raw_%s)),\n", m.GoName, m.GoName))
				} else {
					sb.WriteString(fmt.Sprintf("\t\t%s: SliceData(raw_%s),\n", m.GoName, m.GoName))
				}
			} else {
				if m.GoRawType == "unsafe.Pointer" {
					sb.WriteString(fmt.Sprintf("\t\t%s: unsafe.Pointer(SliceData(s.%s)),\n", m.GoName, m.GoName))
				} else {
					sb.WriteString(fmt.Sprintf("\t\t%s: SliceData(s.%s),\n", m.GoName, m.GoName))
				}
			}
		} else if isOmittedCountMember(m, s) {
			// Find all slice members that use this count
			var matchedSliceMembers []string
			for _, other := range s.Members {
				if other.Api != "" && !indexer.ApiMatches(other.Api, branch.Name) {
					continue
				}
				if !isValidBranchType(other.GoHighType, branch, idx) {
					continue
				}
				if (other.IsSlice || other.IsStringSlice) && other.SliceCountMember == m.Name {
					matchedSliceMembers = append(matchedSliceMembers, other.GoName)
				}
			}
			rawType := m.GoRawType
			if rawType == "" {
				rawType = "uint32"
			}
			if len(matchedSliceMembers) > 0 {
				multiplier := ""
				if strings.HasSuffix(strings.ToLower(m.Name), "size") {
					firstMatched := matchedSliceMembers[0]
					for _, other := range s.Members {
						if other.GoName == firstMatched {
							if strings.HasSuffix(other.GoHighType, "uint32") {
								multiplier = " * 4"
							} else if strings.HasSuffix(other.GoHighType, "uint64") || strings.HasSuffix(other.GoHighType, "uintptr") || strings.HasSuffix(other.GoHighType, "Pointer") {
								multiplier = " * 8"
							}
							break
						}
					}
				}

				var lenExpr string
				if len(matchedSliceMembers) == 1 {
					lenExpr = fmt.Sprintf("len(s.%s)", matchedSliceMembers[0])
				} else {
					var parts []string
					for _, name := range matchedSliceMembers {
						parts = append(parts, fmt.Sprintf("len(s.%s)", name))
					}
					lenExpr = "max(" + strings.Join(parts, ", ") + ")"
				}

				sb.WriteString(fmt.Sprintf("\t\t%s: %s(%s%s),\n", m.GoName, rawType, lenExpr, multiplier))
			} else {
				sb.WriteString(fmt.Sprintf("\t\t%s: 0,\n", m.GoName))
			}
		} else {
			vkName := "Vk" + m.GoHighType
			if _, isStruct := idx.Structs[vkName]; isStruct && !m.IsPointer && !m.IsSlice && len(m.ArrayDimensions) == 0 {
				sb.WriteString(fmt.Sprintf("\t\t%s: *s.%s.Raw(),\n", m.GoName, m.GoName))
			} else {
				sb.WriteString(fmt.Sprintf("\t\t%s: s.%s,\n", m.GoName, m.GoName))
			}
		}
	}

	sb.WriteString("\t}\n\treturn raw\n}\n\n")
	sb.WriteString(fmt.Sprintf("func (s *%s) rawPointer() unsafe.Pointer {\n\tif s == nil {\n\t\treturn nil\n\t}\n\treturn unsafe.Pointer(s.Raw())\n}\n\n", s.GoName))
}
