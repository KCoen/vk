package emitter

import (
	"fmt"
	"sort"
	"strings"

	"github.com/KCoen/vk/generator/indexer"
)

// EmitBranchConstants generates constants_gen.go for an API branch package (vulkan, vulkanbase, vulkansc).
func EmitBranchConstants(branch *indexer.ApiBranchInfo, idx *indexer.Index) (string, error) {
	var sb strings.Builder

	sb.WriteString("// Code generated by vk-gen. DO NOT EDIT.\n\n")
	sb.WriteString(fmt.Sprintf("package %s\n\n", branch.PkgName))

	sb.WriteString("// Version construction and decomposition macros\n")
	sb.WriteString("func MakeVersion(major, minor, patch uint32) uint32 {\n")
	sb.WriteString("\treturn (major << 22) | (minor << 12) | patch\n")
	sb.WriteString("}\n\n")

	sb.WriteString("func MakeApiVersion(variant, major, minor, patch uint32) uint32 {\n")
	sb.WriteString("\treturn (variant << 29) | (major << 22) | (minor << 12) | patch\n")
	sb.WriteString("}\n\n")

	sb.WriteString("func ApiVersionVariant(version uint32) uint32 {\n")
	sb.WriteString("\treturn version >> 29\n")
	sb.WriteString("}\n\n")

	sb.WriteString("func ApiVersionMajor(version uint32) uint32 {\n")
	sb.WriteString("\treturn (version >> 22) & 0x7F\n")
	sb.WriteString("}\n\n")

	sb.WriteString("func ApiVersionMinor(version uint32) uint32 {\n")
	sb.WriteString("\treturn (version >> 12) & 0x3FF\n")
	sb.WriteString("}\n\n")

	sb.WriteString("func ApiVersionPatch(version uint32) uint32 {\n")
	sb.WriteString("\treturn version & 0xFFF\n")
	sb.WriteString("}\n\n")

	sb.WriteString("const (\n")
	sb.WriteString("\tAPI_VERSION_1_0 = (1 << 22) | (0 << 12) | 0\n")
	sb.WriteString("\tAPI_VERSION_1_1 = (1 << 22) | (1 << 12) | 0\n")
	sb.WriteString("\tAPI_VERSION_1_2 = (1 << 22) | (2 << 12) | 0\n")
	sb.WriteString("\tAPI_VERSION_1_3 = (1 << 22) | (3 << 12) | 0\n")
	sb.WriteString("\tAPI_VERSION_1_4 = (1 << 22) | (4 << 12) | 0\n")
	sb.WriteString(")\n\n")

	sb.WriteString("// API Constants\n")
	sb.WriteString("const (\n")

	var names []string
	for name := range branch.Constants {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		c := branch.Constants[name]
		if c.GoName == "" || c.Value == "" {
			continue
		}
		// Skip version macros already generated
		if strings.HasPrefix(c.GoName, "API_VERSION_1_") || c.GoName == "MAKE_VERSION" || c.GoName == "MAKE_API_VERSION" {
			continue
		}

		doc := FormatDocComment(fmt.Sprintf("%s is %s.", c.GoName, c.Name), c.Comment)
		sb.WriteString(doc)
		sb.WriteString(fmt.Sprintf("\t%s = %s\n", c.GoName, c.Value))
	}
	sb.WriteString(")\n")

	return sb.String(), nil
}
